#!/usr/bin/env python3
"""Generate the source-provenance apparatus: where every derivation comes from.

Companion to generate_apparatus.py, which covers claims, routes and the
evidence map.  This one answers the different question an agent asks:
*given a statement, what do I read, and how do I know I am reading the
bytes it was derived from?*

Seven artefacts, all derived:

  gen_concordance.tex   every DERIV statement -> document, SHA-256, locator
  gen_lean.tex          every Lean theorem -> module:line, what it covers
  gen_library.tex       the curated published library, by tier and category
  gen_extraction.tex    the page-level extraction index over local PDFs
  gen_symbols.tex       the join keys: canonical name, spellings, values
  gen_documents.tex     document aliases and their standing
  gen_srcmacros.tex     counts, as \\newcommand

Run from the repository root:

    python paper/master/generate_sources.py
"""

from __future__ import annotations

import collections
import csv
import json
import pathlib
import re
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from generate_apparatus import first_sentences, tex  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "paper" / "master"


def load(name: str):
    with open(ROOT / name, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def short_sha(s: object, n: int = 12) -> str:
    return str(s)[:n] if s else ""


def breakable(s: object) -> str:
    """A path that TeX may wrap.

    \\nolinkurl typesets a path as one unbreakable box, which overfills the
    line for any repository path of realistic depth.  Inside a narrow table
    column the wrapping matters more than the copy-paste fidelity that
    \\nolinkurl protects, so break after each separator instead.
    """
    return tex(s).replace("/", "/\\allowbreak{}").replace("-", "-\\allowbreak{}")


def header(*lines: str) -> list[str]:
    return ["% Generated by paper/master/generate_sources.py.  Do not edit.", *lines]


def small(s: object) -> str:
    """Wrap a cell in a size group.  These tables are dense by design."""
    return "{\\scriptsize " + str(s) + "}"


def mono(s: object) -> str:
    return "{\\scriptsize\\ttfamily " + str(s) + "}"


def row(*cells: str) -> str:
    """One longtable row: cells joined by & and terminated."""
    return " & ".join(cells) + r" \\"


# --------------------------------------------------------------------------
# 1.  The derivation concordance
# --------------------------------------------------------------------------


def make_concordance(docs) -> str:
    """One subsection per source document, one row per statement in it.

    The locator is the part an agent actually needs: it names the heading
    and line range inside the document, so a statement can be found without
    reading the whole file.
    """
    out = header()
    total = sum(len(d.get("statements") or []) for d in docs)
    out.append(
        f"\\noindent The concordance below covers all {total} registered "
        f"derivation statements across {len(docs)} source documents. Each "
        f"document carries the SHA-256 of the bytes its statements were read "
        f"from; if the file has changed, the digest has changed and the "
        f"statements must be re-located rather than assumed.\\par\\medskip"
    )

    for d in sorted(docs, key=lambda x: x["id"]):
        cid = tex(d["id"])
        # The contents line gets the identifier without its CITE: prefix:
        # the full form is wider than the page in a table of contents.
        short = tex(str(d["id"]).split(":", 1)[-1])
        out.append(f"\\subsection*{{{cid}}}")
        out.append(f"\\addcontentsline{{toc}}{{subsection}}{{{short}}}")
        out.append(
            f"\\noindent\\srcpath{{{tex(d.get('path'))}}}\\\\\n"
            f"{{\\footnotesize SHA-256 "
            f"\\texttt{{{short_sha(d.get('sha256'), 16)}}}\\ldots}}"
            f"\\par\\smallskip"
        )
        stmts = d.get("statements") or []
        if not stmts:
            out.append("")
            continue
        out.append("\\begin{longtable}{@{}p{0.30\\linewidth} p{0.30\\linewidth} l l@{}}")
        out.append("\\toprule Statement & Locator & Status & Formal \\\\ \\midrule")
        out.append("\\endfirsthead")
        out.append("\\toprule Statement & Locator & Status & Formal \\\\ \\midrule \\endhead")
        out.append("\\bottomrule\\endfoot")
        for s in stmts:
            sid = str(s["id"]).split(":")[-1]
            # Whole-statement Lean coverage and partial support are different
            # facts and the table keeps them apart.
            if s.get("lean"):
                formal = "full"
            elif s.get("lean_support"):
                formal = "partial"
            else:
                formal = "---"
            out.append(
                row(
                    mono(tex(sid)),
                    small(tex(s.get("locator"))),
                    small(tex(s.get("status"))),
                    small(formal),
                )
            )
        out.append("\\end{longtable}")
        out.append("")
    return "\n".join(out)


def make_open_statements(docs) -> str:
    """The statements that are open or conditional, with what is missing.

    This is the working list: every place the corpus itself records that an
    argument does not close, together with the sentence saying why.
    """
    rows = []
    for d in docs:
        for s in d.get("statements") or []:
            if s.get("status") in ("open", "conditional", "disputed"):
                rows.append((d, s))
    order = {"open": 0, "disputed": 1, "conditional": 2}
    rows.sort(key=lambda r: (order.get(r[1].get("status"), 9), r[1]["id"]))

    out = header()
    out.append(
        f"\\noindent {len(rows)} of the registered derivation statements are "
        f"not recorded as proven. Each is listed with the document it lives "
        f"in, its locator, and the corpus's own sentence on what remains. "
        f"These are the statements an agent can act on directly."
        f"\\par\\medskip"
    )
    # Ledger statements carry inline formulae written for a terminal, with
    # no break points TeX can use; loosen the tolerance rather than reflow
    # mathematics that must be quoted exactly.
    out.append("\\begingroup\\sloppy")
    for d, s in rows:
        sid = str(s["id"])
        out.append(
            f"\\noindent\\textbf{{\\texttt{{\\small {tex(sid)}}}}} "
            f"\\hfill {{\\footnotesize {tex(s.get('status'))}}}\\par"
        )
        out.append(f"{{\\small {first_sentences(s.get('statement'), 3)}}}\\par")
        out.append(
            f"{{\\footnotesize \\srcpath{{{tex(d.get('path'))}}} --- {tex(s.get('locator'))}}}\\par"
        )
        if s.get("hypotheses"):
            hyp = "; ".join(tex(h) for h in s["hypotheses"][:4])
            out.append(f"{{\\footnotesize \\textit{{Hypotheses.}} {hyp}}}\\par")
        if s.get("remaining"):
            out.append(
                f"{{\\footnotesize \\textit{{Remaining.}} "
                f"{first_sentences(s['remaining'], 2)}}}\\par"
            )
        out.append("\\smallskip")
    out.append("\\endgroup")
    return "\n".join(out)


