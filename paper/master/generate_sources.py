# 4.  The page-level extraction index
# --------------------------------------------------------------------------


def make_extraction() -> tuple[str, dict]:
    path = ROOT / "literature/yangmills/extraction/pages.jsonl"
    stats = {"pages": 0, "papers": 0, "topics": 0, "labelled": 0}
    if not path.exists():
        return "% extraction index absent\n", stats

    per_paper = collections.defaultdict(
        lambda: {"pages": 0, "topics": collections.Counter(), "labels": 0}
    )
    topics = collections.Counter()
    for line in path.open(encoding="utf-8"):
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        pid = d.get("paper_id", "?")
        rec = per_paper[pid]
        rec["pages"] += 1
        stats["pages"] += 1
        for t, hits in (d.get("topic_line_hits") or {}).items():
            rec["topics"][t] += len(hits)
            topics[t] += len(hits)
        if d.get("candidate_labels"):
            rec["labels"] += 1
            stats["labelled"] += 1
    stats["papers"] = len(per_paper)
    stats["topics"] = len(topics)

    out = header()
    out.append(
        f"\\noindent {stats['pages']} extracted pages across "
        f"{stats['papers']} works, indexed by topic and line. A row says how "
        f"many pages of that work are searchable and which topics occur in "
        f"it; the index records \\emph{{locators}}, not text, so the reading "
        f"copy under \\srcpath{{literature/inbox/<ID>/extracted/}} is where "
        f"the words are. A hit may be a citation or an extraction error: the "
        f"index is a search aid and certifies nothing.\\par\\medskip"
    )
    out.append("\\begin{longtable}{@{}l r r p{0.46\\linewidth}@{}}")
    out.append("\\toprule Work & Pages & Labelled & Topics present \\\\ \\midrule")
    out.append("\\endfirsthead")
    out.append("\\toprule Work & Pages & Labelled & Topics present \\\\ \\midrule \\endhead")
    out.append("\\bottomrule\\endfoot")
    for pid in sorted(per_paper, key=lambda p: -per_paper[p]["pages"]):
        rec = per_paper[pid]
        tops = ", ".join(f"{tex(t)} ({n})" for t, n in rec["topics"].most_common(6))
        out.append(
            row(
                mono(tex(pid)),
                str(rec["pages"]),
                str(rec["labels"]),
                small(tops or "---"),
            )
        )
    out.append("\\end{longtable}")
    out.append("")
    out.append(
        "\\noindent Searchable topics, with total line hits: {}.\\par".format(
            ", ".join(f"\\texttt{{{tex(t)}}} ({n})" for t, n in topics.most_common())
        )
    )
    return "\n".join(out), stats


