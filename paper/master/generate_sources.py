def make_symbols(symbols) -> str:
    out = header()
    out.append(
        "\\noindent The join keys of this corpus are exact values and "
        "spellings, not concepts: no natural-language query retrieves "
        "$109151/249696$. The registry below is what makes a value findable "
        "across a document written in one notation, code written in another, "
        "and a claim recorded in a third.\\par\\medskip"
    )
    for s in sorted(symbols, key=lambda x: x["id"]):
        out.append(
            "\\noindent\\textbf{{\\texttt{{{}}}}}".format(tex(s.get("canonical") or s["id"]))
        )
        if s.get("values"):
            out.append(
                " \\hfill {{\\footnotesize values: {}}}".format(
                    ", ".join(f"\\texttt{{{tex(v)}}}" for v in s["values"][:6])
                )
            )
        out.append("\\par")
        out.append("{{\\small {}}}\\par".format(first_sentences(s.get("meaning"), 2)))
        bits = []
        if s.get("corpus_spellings"):
            bits.append(
                "corpus spellings: "
                + ", ".join(f"\\texttt{{{tex(x)}}}" for x in s["corpus_spellings"][:6])
            )
        if s.get("code_names"):
            bits.append(
                "in code: " + ", ".join(f"\\texttt{{{tex(x)}}}" for x in s["code_names"][:6])
            )
        if s.get("claims"):
            bits.append("claims: " + ", ".join(f"\\texttt{{{tex(x)}}}" for x in s["claims"][:8]))
        if bits:
            out.append("{{\\footnotesize {}}}\\par".format(" \\quad ".join(bits)))
        out.append("\\smallskip")
    return "\n".join(out)


