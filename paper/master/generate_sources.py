def read_manifest(rel: str):
    p = ROOT / rel
    if not p.exists():
        return []
    with open(p, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


CATEGORY_NAME = {
    "hamiltonian_quantum": "Hamiltonian and quantum-simulation formulations",
    "rigorous_lgt": "Rigorous lattice Yang--Mills",
    "spectrum": "Glueball spectrum and continuum limits",
    "effective_hamiltonian": "Effective Hamiltonians and strong coupling",
    "weingarten": "Weingarten and Haar integration",
    "flat_bands": "Flat bands and compact localized states",
    "flux_strings": "Flux tubes, strings and torelons",
    "strong_coupling": "Strong-coupling expansions",
    "spectral_methods": "Spectral extraction and operator overlap",
}


def make_library(v1, v2) -> str:
    rows = [dict(r, volume="1") for r in v1] + [dict(r, volume="2") for r in v2]
    by_cat = collections.defaultdict(list)
    for r in rows:
        by_cat[r.get("category", "other")].append(r)

    out = header()
    out.append(
        f"\\noindent {len(rows)} acquired papers, all with local full text, "
        f"grouped by the library's own categories. \\emph{{Connection}} is "
        f"the curated one-line statement of what the paper bears on in this "
        f"program; it is a reading note, not an evidence edge. The evidence "
        f"edges are the separate, smaller, verified set in "
        f"\\S\\ref{{sec:external}}. A paper here has been \\emph{{obtained}}, "
        f"which is not the same as \\emph{{read against a claim}}."
        f"\\par\\medskip"
    )
    for cat in sorted(by_cat, key=lambda c: -len(by_cat[c])):
        name = CATEGORY_NAME.get(cat, cat.replace("_", " ").title())
        out.append(f"\\subsection*{{{tex(name)}}}")
        out.append(f"\\addcontentsline{{toc}}{{subsection}}{{{tex(name)}}}")
        out.append("\\begin{longtable}{@{}l p{0.40\\linewidth} l p{0.28\\linewidth}@{}}")
        out.append("\\toprule Year & Title & arXiv & Connection \\\\ \\midrule")
        out.append("\\endfirsthead")
        out.append("\\toprule Year & Title & arXiv & Connection \\\\ \\midrule \\endhead")
        out.append("\\bottomrule\\endfoot")

        def by_year(x):
            return (-int(x.get("year") or 0), x.get("title", ""))

        for r in sorted(by_cat[cat], key=by_year):
            out.append(
                row(
                    tex(r.get("year")),
                    small(tex(r.get("title"))),
                    small("\\texttt{" + tex(r.get("arxiv_id")) + "}"),
                    small(tex(r.get("workhouse_connection"))),
                )
            )
        out.append("\\end{longtable}")
        out.append("")
    return "\n".join(out)


