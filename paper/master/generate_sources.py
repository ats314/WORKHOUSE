# 6.  Document aliases and their standing
# --------------------------------------------------------------------------


def make_documents(aliases) -> str:
    by_standing = collections.defaultdict(list)
    for a in aliases:
        by_standing[a.get("standing", "unrecorded")].append(a)

    out = header()
    out.append(
        f"\\noindent {len(aliases)} source documents carry a registered alias "
        f"and a \\emph{{standing}}. Standing is the single most important "
        f"field for an agent reading the archive: it says whether a document "
        f"is current, superseded, or preserved only as evidence of a stage. "
        f"A superseded document is not deleted and reads exactly like a "
        f"current one.\\par\\medskip"
    )
    for standing in sorted(by_standing, key=lambda s: -len(by_standing[s])):
        group = by_standing[standing]
        out.append(f"\\subsection*{{Standing: {tex(standing)} ({len(group)})}}")
        out.append(f"\\addcontentsline{{toc}}{{subsection}}{{Standing: {tex(standing)}}}")
        # Absolute column widths, not fractions of \linewidth.  Aliases and
        # repository paths are both long, so neither column can be left to
        # size itself; and a fraction of \linewidth is resolved late enough
        # inside longtable that the surrounding context can change it.
        # 2.0in + 4.2in + separation fits the 6.5in text block.
        out.append("\\begin{longtable}{@{}p{2.0in} p{4.2in}@{}}")
        out.append("\\toprule Alias & Path \\\\ \\midrule")
        out.append("\\endfirsthead")
        out.append("\\toprule Alias & Path \\\\ \\midrule \\endhead")
        out.append("\\bottomrule\\endfoot")
        for a in sorted(group, key=lambda x: str(x.get("alias") or "")):
            out.append(
                "{{\\scriptsize\\ttfamily {}}} & {{\\scriptsize\\ttfamily {}}} \\\\".format(
                    breakable(a.get("alias")), breakable(a.get("path"))
                )
            )
        out.append("\\end{longtable}")
        out.append("")
    return "\n".join(out)


