# 2.  The Lean tree
# --------------------------------------------------------------------------


def lean_locations() -> dict:
    """Map theorem name -> "module:line", read from the Lean sources.

    The dependency export records qualified names but not positions, and
    positions are what a reader needs, so they are recovered here from the
    files themselves rather than transcribed.
    """
    loc = {}
    pat = re.compile(
        r"^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+)?"
        r"(?:theorem|lemma)\s+([A-Za-z_][A-Za-z0-9_'.]*)"
    )
    for f in sorted((ROOT / "lean").rglob("*.lean")):
        try:
            lines = f.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        rel = f.relative_to(ROOT).as_posix()
        for i, line in enumerate(lines, 1):
            m = pat.match(line)
            if m:
                loc.setdefault(m.group(1), f"{rel}:{i}")
    return loc


def make_lean(theorems, locations) -> str:
    by_module = collections.defaultdict(list)
    for t in theorems:
        where = locations.get(t["name"], "")
        module = where.split(":")[0].split("/")[-1] if where else "(unlocated)"
        by_module[module].append((t, where))

    total = len(theorems)
    promotes = sum(1 for t in theorems if t.get("promotes"))
    formalizes = sum(1 for t in theorems if t.get("formalizes"))
    located = sum(1 for t in theorems if locations.get(t["name"]))

    out = header()
    out.append(
        f"\\noindent {total} registered theorems across {len(by_module)} "
        f"modules. \\emph{{Promotes}} means the theorem proves an entire "
        f"named check and so carries its verification tier; "
        f"\\emph{{formalizes}} means it is linked to a catalogue record. "
        f"Only {promotes} of {total} carry a \\texttt{{promotes}} link, and "
        f"reading the difference as a defect would be a mistake: most "
        f"theorems are ingredients, and the registry keeps ingredient and "
        f"whole-statement coverage apart on purpose.\\par\\medskip"
    )
    for module in sorted(by_module):
        out.append(f"\\subsection*{{{tex(module)}}}")
        out.append(f"\\addcontentsline{{toc}}{{subsection}}{{{tex(module)}}}")
        out.append("\\begin{longtable}{@{}p{0.32\\linewidth} l p{0.44\\linewidth}@{}}")
        out.append("\\toprule Theorem & Line & Formalizes / promotes \\\\ \\midrule")
        out.append("\\endfirsthead")
        out.append("\\toprule Theorem & Line & Formalizes / promotes \\\\ \\midrule \\endhead")
        out.append("\\bottomrule\\endfoot")
        for t, where in sorted(by_module[module], key=lambda x: x[0]["name"]):
            line = where.split(":")[-1] if where else ""
            # Escape first, then add markup: running tex() over the markup
            # turns \textbf into literal backslash-t-e-x-t-b-f in the PDF.
            links = [tex(x) for x in (t.get("formalizes") or [])]
            links += [
                "\\textbf{promotes} " + tex(p) for p in (t.get("promotes") or [])
            ]
            out.append(
                row(
                    mono(tex(t["name"])),
                    small(line),
                    small("; ".join(links) if links else "---"),
                )
            )
        out.append("\\end{longtable}")
        out.append("")
    out.append(f"% located {located} of {total}; formalizes {formalizes}")
    return "\n".join(out)


