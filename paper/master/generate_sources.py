def graph_stats() -> dict:
    path = ROOT / "index/graph.jsonl"
    kinds = collections.Counter()
    n = 0
    if path.exists():
        for line in path.open(encoding="utf-8"):
            n += 1
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            if d.get("kind"):
                kinds[d["kind"]] += 1
    return {"lines": n, "kinds": kinds}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)

    ds = load("ledger/derivation_statements.yaml")
    docs = ds["documents"]
    theorems = load("ledger/theorems.yaml")["theorems"]
    symbols = load("ledger/symbols.yaml")["symbols"]
    aliases = load("ledger/documents.yaml")["aliases"]
    notes = load("ledger/notes.yaml")

    v1 = read_manifest("literature/library/paper_manifest.csv")
    v2 = read_manifest("literature/library/volume2/paper_manifest.csv")
    extraction, xstats = make_extraction()
    g = graph_stats()

    n_deriv = sum(len(d.get("statements") or []) for d in docs)
    n_open = sum(
        1
        for d in docs
        for s in (d.get("statements") or [])
        if s.get("status") in ("open", "conditional", "disputed")
    )
    locations = lean_locations()
    n_lean_modules = len({v.split(":")[0] for v in locations.values()})

    artefacts = {
        "gen_concordance.tex": make_concordance(docs),
        "gen_open_statements.tex": make_open_statements(docs),
        "gen_lean.tex": make_lean(theorems, locations),
        "gen_library.tex": make_library(v1, v2),
        "gen_extraction.tex": extraction,
        "gen_symbols.tex": make_symbols(symbols),
        "gen_documents.tex": make_documents(aliases),
        "gen_srcmacros.tex": "\n".join(
            header(
                "% Counts for the source-provenance sections.",
                f"\\newcommand{{\\CiteDocs}}{{{len(docs)}}}",
                f"\\newcommand{{\\DerivStatements}}{{{n_deriv}}}",
                f"\\newcommand{{\\DerivOpen}}{{{n_open}}}",
                f"\\newcommand{{\\LeanModules}}{{{n_lean_modules}}}",
                f"\\newcommand{{\\LibraryPapers}}{{{len(v1) + len(v2)}}}",
                f"\\newcommand{{\\LibraryVolOne}}{{{len(v1)}}}",
                f"\\newcommand{{\\LibraryVolTwo}}{{{len(v2)}}}",
                f"\\newcommand{{\\ExtractedPages}}{{{xstats['pages']}}}",
                f"\\newcommand{{\\ExtractedWorks}}{{{xstats['papers']}}}",
                f"\\newcommand{{\\ExtractedTopics}}{{{xstats['topics']}}}",
                f"\\newcommand{{\\SymbolCount}}{{{len(symbols)}}}",
                f"\\newcommand{{\\AliasCount}}{{{len(aliases)}}}",
                f"\\newcommand{{\\NoteArchives}}{{{len(notes.get('archives') or [])}}}",
                f"\\newcommand{{\\NoteReviews}}{{{len(notes.get('reviews') or [])}}}",
                f"\\newcommand{{\\GraphEdges}}{{{g['lines']}}}",
                f"\\newcommand{{\\GraphEdgeKinds}}{{{len(g['kinds'])}}}",
            )
        ),
    }

    for name, body in artefacts.items():
        (OUT / name).write_text(body + "\n", encoding="utf-8")
        print(f"wrote {name}: {len(body.splitlines())} lines")

    print(
        f"\nsources: {len(docs)} cite docs / {n_deriv} deriv statements "
        f"({n_open} not proven), {len(theorems)} lean theorems "
        f"({len(locations)} located), {len(v1) + len(v2)} library papers, "
        f"{xstats['pages']} extracted pages, {len(symbols)} symbols, "
        f"{len(aliases)} aliases, {g['lines']} graph edges"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
