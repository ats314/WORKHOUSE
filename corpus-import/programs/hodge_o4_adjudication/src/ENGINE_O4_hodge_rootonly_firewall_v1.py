#!/usr/bin/env python3
"""Cold, dependency-free firewalls for the HODGE SU(3) O(u^4) path.

This file intentionally does *not* import or patch the historical v10a23/v10a25
runtime.  It provides two independent checks that must pass before that runtime
is touched again:

1. An exact SU(3) character-basis calculation of the one-plaquette C-odd gap
   through fourth order.  All arithmetic is ``fractions.Fraction``.
2. A layer-distance proof that a Q2-W-Q2 block first contributes at fifth
   order, so any (2,5)/(5,2) seven-occurrence Haar request in the O(u^4) path is
   evidence that an unnecessary full restricted-Hamiltonian build was reached.

Optional ``--audit PATH`` performs a conservative static scan for the concrete
regression recorded in the failed repair.  It accepts Python or Jupyter files.
Because arbitrary Python reflection and imported helpers cannot be proven safe
statically, this scan is non-authoritative and never authorizes production.  It
does not replace an executed root-path census with poisoned W22/qhaar sentinels.

Exit status is zero only when every requested gate passes.
"""

from __future__ import annotations

